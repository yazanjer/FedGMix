"""Pilot 2 step: build P4 = (best of P1-P3 by tuning-seed validation macro-F1) + guarded CCVR.

Reads outputs/index/tune_v3_selection.json (written by select_hparams.py); writes
configs/method/sfspcl_v3x_ccvr.yaml. Selection never looks at test metrics.
"""
import json
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
out = Path(sys.argv[1] if len(sys.argv) > 1 else "outputs_v2")
sel = json.loads((out / "index" / "tune_v3_selection.json").read_text())["selected"]
cands = ["sfspcl_m_ntd", "sfspcl_cm", "sfspcl_m_fa"]
x = max(cands, key=lambda m: sel[m]["val_macro_f1_mean"])
cfg = yaml.safe_load((REPO / "configs/method" / f"{x}.yaml").read_text())
for k, v in sel[x].items():
    if k.startswith("method."):
        cfg[k.split(".", 1)[1]] = v
cfg.update(name="sfspcl_v3x_ccvr", ccvr=True, ccvr_samples=2000, ccvr_epochs=10, ccvr_lr=0.1, ccvr_guard=True)
head = f"# Pilot 2 candidate P4, generated by scripts/make_v3x.py: X = {x} (tuning-seed val {sel[x]['val_macro_f1_mean']}) + guarded CCVR (ccvr_lr 0.1 from tune_v2).\n"
(REPO / "configs/method/sfspcl_v3x_ccvr.yaml").write_text(head + yaml.safe_dump(cfg, sort_keys=False))
print(x, sel[x])
