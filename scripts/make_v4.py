"""Pilot 3 step: build sfspcl_v_ccvr = sfspcl_v at its tuned virtual ratio + guarded CCVR (ccvr_lr 0.1)."""
import json
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
out = Path(sys.argv[1] if len(sys.argv) > 1 else "outputs_v2")
sel = json.loads((out / "index" / "tune_v4_selection.json").read_text())["selected"]["sfspcl_v"]
cfg = yaml.safe_load((REPO / "configs/method/sfspcl_v.yaml").read_text())
cfg["virtual"] = sel["method.virtual"]
cfg.update(name="sfspcl_v_ccvr", ccvr=True, ccvr_samples=2000, ccvr_epochs=10, ccvr_lr=0.1, ccvr_guard=True)
(REPO / "configs/method/sfspcl_v_ccvr.yaml").write_text(
    f"# Pilot 3 candidate V+CCVR, generated by scripts/make_v4.py (virtual = {sel['method.virtual']} from tune_v4).\n"
    + yaml.safe_dump(cfg, sort_keys=False))
print(sel)
